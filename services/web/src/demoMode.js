export function setExecutiveDemoPhase(phaseNumber) {
  const state = readState();
  const executive = clone(state.executive_demo || seedState.executive_demo);
  const total = (executive.phases || []).length || EXECUTIVE_DEMO_TOTAL;
  executive.active_phase = clamp(Number(phaseNumber || 1), 1, total);
  state.executive_demo = executive;
  writeState(state);
  return getExecutiveDemoState();
}

export function nextExecutiveDemoPhase() {
  const current = getExecutiveDemoState();
  return setExecutiveDemoPhase((current.active_phase || 1) + 1);
}

export function prevExecutiveDemoPhase() {
  const current = getExecutiveDemoState();
  return setExecutiveDemoPhase((current.active_phase || 1) - 1);
}

export function resetExecutiveDemoPhase() {
  return setExecutiveDemoPhase(1);
}

